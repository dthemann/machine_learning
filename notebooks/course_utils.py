DATA_DIR = Path(__file__).resolve().parent.parent / "data"
RANDOM_STATE = 42

# A categorical palette that stays distinguishable for the common forms of
# colour-vision deficiency (validated for adjacent-pair separation).
PALETTE = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#4a3aa7", "#e34948"]


def set_style() -> None:
    """Apply the course-wide plotting style (colour-blind-safe palette, light grid, no chart junk)."""
    mpl.rcParams.update({
        "figure.figsize": (7.5, 4.5),
        "figure.dpi": 100,
        "axes.prop_cycle": mpl.cycler(color=PALETTE),
        "axes.grid": True,
        "grid.alpha": 0.3,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.titlesize": 12,
        "axes.titleweight": "semibold",
        "axes.labelsize": 10.5,
        "legend.frameon": False,
        "lines.linewidth": 2,
        "image.cmap": "viridis",
        "savefig.bbox": "tight",
    })


def plot_decision_boundary(model, X, y, ax=None, resolution: int = 300, alpha: float = 0.25,
                           title: str | None = None, feature_names=("feature 1", "feature 2"),
                           proba: bool = False, legend: bool = True):
    """Draw the decision regions of a fitted 2-D classifier together with the data.

    Parameters
    ----------
    model : fitted estimator with ``predict`` (and ``predict_proba`` if proba=True)
    X : array of shape (n_samples, 2)
    y : array of class labels
    proba : if True and the classifier is binary, shade P(y=1) instead of the hard prediction
    legend : set to False in panel grids where one shared legend is enough
    """
    X = np.asarray(X)
    y = np.asarray(y)
    if ax is None:
        _, ax = plt.subplots()
    x_min, x_max = X[:, 0].min(), X[:, 0].max()
    y_min, y_max = X[:, 1].min(), X[:, 1].max()
    pad_x, pad_y = 0.08 * (x_max - x_min + 1e-9), 0.08 * (y_max - y_min + 1e-9)
    xx, yy = np.meshgrid(np.linspace(x_min - pad_x, x_max + pad_x, resolution),
                         np.linspace(y_min - pad_y, y_max + pad_y, resolution))
    grid = np.c_[xx.ravel(), yy.ravel()]
    classes = np.unique(y)
    cmap = ListedColormap(PALETTE[: max(len(classes), 2)])
    if proba and len(classes) == 2:
        zz = model.predict_proba(grid)[:, 1].reshape(xx.shape)
        cs = ax.contourf(xx, yy, zz, levels=np.linspace(0, 1, 11), cmap="RdBu_r", alpha=0.6)
        plt.colorbar(cs, ax=ax, label="P(y = 1)")
        ax.contour(xx, yy, zz, levels=[0.5], colors="k", linewidths=1.2)
    else:
        zz = model.predict(grid)
        # map labels to 0..k-1 for colouring
        lookup = {c: i for i, c in enumerate(classes)}
        zz = np.vectorize(lookup.get)(zz).reshape(xx.shape)
        ax.contourf(xx, yy, zz, levels=np.arange(-0.5, len(classes) + 0.5, 1), cmap=cmap, alpha=alpha)
    for i, c in enumerate(classes):
        m = y == c
        ax.scatter(X[m, 0], X[m, 1], s=22, color=PALETTE[i % len(PALETTE)], edgecolor="white",
                   linewidth=0.5, label=f"class {c}")
    ax.set_xlabel(feature_names[0])
    ax.set_ylabel(feature_names[1])
    ax.grid(False)
    if title:
        ax.set_title(title)
    if legend:
        ax.legend(loc="best")
    return ax


