def _notice(msg: str) -> None:
    print(f"[course_utils] {msg}")


def load_california_housing(as_frame: bool = True):
    """California housing (Pace & Barry, 1997) via scikit-learn; synthetic stand-in when offline."""
    try:
        from sklearn.datasets import fetch_california_housing
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            data = fetch_california_housing(as_frame=as_frame)
        return data
    except Exception as exc:  # no internet, blocked download, ...
        _notice(f"could not download California housing ({type(exc).__name__}); using a synthetic stand-in "
                "with the same columns. Results will differ from the real data.")
        rng = np.random.default_rng(RANDOM_STATE)
        n = 20640
        med_inc = np.clip(rng.lognormal(1.2, 0.5, n), 0.5, 15)
        house_age = rng.integers(1, 52, n).astype(float)
        ave_rooms = np.clip(rng.normal(5.4, 1.2, n), 1, 15)
        ave_bedrms = np.clip(ave_rooms * rng.normal(0.2, 0.03, n), 0.5, 5)
        population = np.clip(rng.lognormal(7.0, 0.8, n), 3, 30000)
        ave_occup = np.clip(rng.normal(3.0, 0.8, n), 1, 12)
        latitude = rng.uniform(32.5, 42.0, n)
        longitude = rng.uniform(-124.3, -114.3, n)
        coast = np.exp(-((longitude + 118.5) ** 2 + (latitude - 34.0) ** 2) / 6) + np.exp(-((longitude + 122.4) ** 2 + (latitude - 37.8) ** 2) / 3)
        price = (0.4 + 0.55 * med_inc - 0.015 * house_age + 0.05 * ave_rooms - 0.12 * ave_occup + 2.2 * coast
                 + rng.normal(0, 0.45, n))
        price = np.clip(price, 0.15, 5.0)
        frame = pd.DataFrame({"MedInc": med_inc, "HouseAge": house_age, "AveRooms": ave_rooms, "AveBedrms": ave_bedrms,
                              "Population": population, "AveOccup": ave_occup, "Latitude": latitude,
                              "Longitude": longitude})
        target = pd.Series(price, name="MedHouseVal")

        class _Bunch(dict):
            def __getattr__(self, k):
                return self[k]
        return _Bunch(data=frame if as_frame else frame.values, target=target if as_frame else target.values,
                      frame=pd.concat([frame, target], axis=1), feature_names=list(frame.columns),
                      target_names=["MedHouseVal"], DESCR="synthetic stand-in for the California housing data")


def load_penguins() -> pd.DataFrame:
    """Palmer penguins (Horst, Hill & Gorman, 2020) via seaborn; synthetic stand-in when offline."""
    try:
        import seaborn as sns
        return sns.load_dataset("penguins")
    except Exception as exc:
        _notice(f"could not download the penguins data ({type(exc).__name__}); using a synthetic stand-in.")
        rng = np.random.default_rng(RANDOM_STATE)
        specs = {  # species: (bill_length, bill_depth, flipper_length, body_mass, islands)
            "Adelie": ((38.8, 2.7), (18.3, 1.2), (190, 6.5), (3700, 460), ["Torgersen", "Biscoe", "Dream"]),
            "Chinstrap": ((48.8, 3.3), (18.4, 1.1), (196, 7.1), (3730, 380), ["Dream"]),
            "Gentoo": ((47.5, 3.1), (15.0, 1.0), (217, 6.5), (5080, 500), ["Biscoe"]),
        }
        rows = []
        for species, n in (("Adelie", 152), ("Chinstrap", 68), ("Gentoo", 124)):
            bl, bd, fl, bm, islands = specs[species]
            sex = rng.choice(["Male", "Female"], n)
            shift = np.where(sex == "Male", 1.0, -1.0)
            rows.append(pd.DataFrame({
                "species": species,
                "island": rng.choice(islands, n),
                "bill_length_mm": rng.normal(bl[0], bl[1], n) + 1.5 * shift,
                "bill_depth_mm": rng.normal(bd[0], bd[1], n) + 0.6 * shift,
                "flipper_length_mm": rng.normal(fl[0], fl[1], n) + 3 * shift,
                "body_mass_g": rng.normal(bm[0], bm[1], n) + 250 * shift,
                "sex": sex,
            }))
        df = pd.concat(rows, ignore_index=True).sample(frac=1, random_state=RANDOM_STATE).reset_index(drop=True)
        for col in ["bill_length_mm", "bill_depth_mm", "flipper_length_mm", "body_mass_g"]:
            df[col] = df[col].round(1)
            df.loc[rng.random(len(df)) < 0.01, col] = np.nan
        df.loc[rng.random(len(df)) < 0.03, "sex"] = None
        return df


def load_adult() -> pd.DataFrame:
    """The 'Adult' census income data (Kohavi, 1996) via OpenML; falls back to the bundled loan data."""
    try:
        from sklearn.datasets import fetch_openml
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            adult = fetch_openml("adult", version=2, as_frame=True)
        df = adult.frame.copy()
        df["income"] = (df["class"].astype(str).str.contains(">50K")).astype(int)
        return df.drop(columns=["class"])
    except Exception as exc:
        _notice(f"could not download the Adult data ({type(exc).__name__}); use load_loans() instead "
                "(bundled, with a documented bias mechanism).")
        return load_loans()


def load_newsgroups(categories=("sci.space", "rec.sport.hockey", "talk.politics.misc", "comp.graphics")):
    """A 4-category subset of 20 Newsgroups (Lang, 1995); falls back to the bundled review corpus."""
    try:
        from sklearn.datasets import fetch_20newsgroups
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            data = fetch_20newsgroups(subset="all", categories=list(categories),
                                      remove=("headers", "footers", "quotes"), random_state=RANDOM_STATE)
        return pd.DataFrame({"text": data.data, "label": [data.target_names[t] for t in data.target]})
    except Exception as exc:
        _notice(f"could not download 20 Newsgroups ({type(exc).__name__}); using the bundled synthetic review corpus.")
        df = load_reviews()
        return pd.DataFrame({"text": df["text"], "label": df["product"]})


