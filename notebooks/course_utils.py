def load_churn(raw: bool = False) -> pd.DataFrame:
    """Synthetic telco-style customer churn data (5 005 rows incl. duplicates).

    ``raw=True`` returns the file exactly as shipped (with missing values, duplicated rows,
    inconsistent capitalisation and a few outliers) so that it can be cleaned in the course.
    ``raw=False`` applies the cleaning steps developed in notebook 04.
    """
    df = pd.read_csv(DATA_DIR / "customer_churn.csv", parse_dates=["signup_date"])
    if raw:
        return df
    df = df.drop_duplicates(subset="customer_id").copy()
    df["region"] = df["region"].str.title()
    df.loc[df["monthly_charges"] > 200, "monthly_charges"] = np.nan
    return df.reset_index(drop=True)


